#ifndef __ALGORITHM_PID_H__
#define __ALGORITHM_PID_H__

#include <stdint.h>

/* ============================================================================
 * 通用位置式 PID（纯浮点 / 可重入 / 无动态内存 / 无全局状态）
 *
 * 为什么是"位置式"而不是"增量式"：
 *   平衡车的输出是"占空比绝对值"，0 就是停。增量式算的是 Δu，
 *   一旦某一拍因为超时被跳过，这个 Δ 就永久丢了，输出会永远偏一个量；
 *   位置式每拍都由"当前状态"从头算，丢一拍只少纠一次，下一拍自动追回来。
 *   对"会丢拍的中断控制环"，位置式天然更耐操。
 *
 * 抗饱和选型：clamp（积分钳位 + 条件积分），不用 back-calculation。
 *   back-calculation 要额外引一个"回算时间常数 Tt"，本质上是第二个调不出来的
 *   增益；clamp 只要一个物理上限 integ_max，行为完全可预测：积分项永远到不了
 *   integ_max 以上，也就没有"退出饱和后还要反向积分半天才动"的滞后。
 *   代价是：如果 integ_max 设得过大，饱和期间积分仍会顶到上限，只是不会越界。
 *
 * 微分作用于测量值（d_on_measure = 1）：
 *   微分作用在误差上时，设定值一跳（比如转向目标从 0 改成 30°/s），
 *   误差瞬间跳变 → 微分项给出一个尖峰（derivative kick），车会抖一下。
 *   作用在测量值上就没这个问题：设定值随便跳，D 项只看"实际量变化多快"。
 *
 * 可重入：所有状态都在调用者给的 Pid_t 里，函数内部没有 static 变量。
 *   一个 Pid_t 就是一个独立的控制器，想开几个开几个（直立环 + 转向环就是两个）。
 * ========================================================================== */

/* dt 的合法上限（秒）。
 * 超过它说明控制节拍早就不对了（丢拍/进调试器/被高优先级中断卡住），
 * 这时候如果还按 dt 去做微分和积分，会算出一个巨大的假值，比"本拍不出力"危险得多。 */
#define PID_DT_MAX_S        (0.5f)

typedef struct
{
    /* ---------- 参数（Pid_Init 写入，运行期也允许直接改，方便在线整定） ---------- */
    float kp;               /* 比例：误差 → 输出，决定"反应有多硬" */
    float ki;               /* 积分：误差 × 时间 → 输出，消静差，但会引入相位滞后 */
    float kd;               /* 微分：误差变化率 → 输出，起阻尼作用，压超调 */

    float out_max;          /* 输出限幅（绝对值）。<= 0 表示不限（不建议） */
    float integ_max;        /* 积分项限幅（绝对值，单位同输出，已含 ki）。<= 0 表示不限 */

    uint8_t d_on_measure;   /* 1 = 微分作用于测量值（推荐）；0 = 微分作用于误差 */

    /* ---------- 运行状态（Reset 清零，外部不要手改） ---------- */
    float integral;         /* 当前积分项累加值（已经是"输出量纲"，即乘过 ki·dt 的） */
    float prev_measure;     /* 上一拍的测量值，用于对测量值差分 */
    float prev_setpoint;    /* 上一拍的设定值，用于对误差差分（d_on_measure = 0 时才用） */
    uint8_t primed;         /* 首拍标志：0 表示还没拿到有效上一拍，本拍不出微分 */
} Pid_t;

/* 初始化（内部会调 Reset）。参数非法（null 指针）时直接返回，不产生副作用。 */
void Pid_Init(Pid_t *pid, float kp, float ki, float kd,
              float out_max, float integ_max, uint8_t d_on_measure);

/* 清空积分和历史值：使能/复位/重新起控时调用，
 * 否则上一轮攒的积分会带进新一轮，出现"刚使能就满占空比"的怪现象。 */
void Pid_Reset(Pid_t *pid);

/* 标准入口：rate（测量值的导数）由本函数用 prev_measure 自己差出来。
 * 适合"没有角速度计、只有角度"的场合。首拍不出微分（避免尖峰）。 */
float Pid_Update(Pid_t *pid, float setpoint, float measure, float dt);

/* 推荐入口：rate 由调用者直接给（平衡车这里给陀螺原始角速度，单位必须与
 * measure 的时间导数同量纲）。
 * 为什么不用 Pid_Update：对"互补滤波后的角度"做差分，等于把滤波里那 2% 的
 * 加速度修正噪声也拿去微分了，D 项会抖；而陀螺本来就是角速度，直接喂进来
 * 不需要差分，噪声特性好一个数量级。 */
float Pid_UpdateWithRate(Pid_t *pid, float setpoint, float measure, float rate, float dt);

#endif /* __ALGORITHM_PID_H__ */
